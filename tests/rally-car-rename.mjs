import assert from 'node:assert/strict';
import {rallyCarTuning,rallyCarConfig} from '../RallyCarConfig.js';
import {audiTuning,audiConfig} from '../AudiConfig.js';
import {loadTuning,tuningKey,tuningValue,setTuning,resetTuning,exportRallyCarTuning,exportAudioTuning,fieldPath,tuningFields} from '../TuningStore.js';

assert.equal(audiTuning,rallyCarTuning);
assert.equal(audiConfig,rallyCarConfig,'legacy module reuses the canonical implementation');
const values=new Map(),storage={getItem:key=>values.get(key)??null,setItem:(key,value)=>values.set(key,value)};
const save=overrides=>storage.setItem(tuningKey(),JSON.stringify({version:1,overrides}));
save({'audiTuning.handling.acceleration':31,'audiTuning.acceleration':29,'audioConfig.sounds.audi-electric.volume':23,'audioConfig.sounds.audi-tires.enabled':false});
loadTuning(storage);
assert.equal(tuningValue('rallyCarTuning.handling.acceleration'),31);
assert.equal(tuningValue('rallyCarTuning.acceleration'),29);
assert.equal(tuningValue('audioConfig.sounds.rally-car-electric.volume'),23);
assert.equal(tuningValue('audioConfig.sounds.rally-car-tires.enabled'),false);
assert.equal(fieldPath(tuningFields.find(f=>f.id==='drive.acceleration'),'audi'),fieldPath(tuningFields.find(f=>f.id==='drive.acceleration'),'rally-car'));
setTuning('rallyCarTuning.handling.acceleration',32,storage);
assert(!/audiTuning|sounds\.audi-/.test(storage.getItem(tuningKey())),'next save persists migrated canonical names only');
loadTuning(storage);assert.equal(tuningValue('audioConfig.sounds.rally-car-electric.volume'),23);
save({'rallyCarTuning.handling.acceleration':35,'audiTuning.handling.acceleration':31,'audioConfig.sounds.rally-car-electric.volume':40,'audioConfig.sounds.audi-electric.volume':23});
loadTuning(storage);
assert.equal(tuningValue('rallyCarTuning.handling.acceleration'),35,'explicit canonical value wins regardless of record order');
assert.equal(tuningValue('audioConfig.sounds.rally-car-electric.volume'),40);
const vehicle=await import('data:text/javascript,'+encodeURIComponent(exportRallyCarTuning()));
assert.equal(vehicle.rallyCarConfig().handling.acceleration,35);
const audio=await import('data:text/javascript,'+encodeURIComponent(exportAudioTuning()));
assert.equal(audio.audioConfig.sounds['rally-car-electric'].volume,40);
assert(!/audiTuning|audiConfig|sounds\.audi-/.test(exportRallyCarTuning()+exportAudioTuning()));
loadTuning({getItem(){throw new Error('blocked');}});
assert.equal(tuningValue('rallyCarTuning.handling.acceleration'),25,'restricted storage preserves defaults');
resetTuning(undefined,storage);
console.log('PASS Rally Car rename: shared legacy config, old/mixed settings migration, canonical exports/persistence and blocked storage.');
