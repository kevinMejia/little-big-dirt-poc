import assert from 'node:assert/strict';
import { HillSpeedPhysics } from '../HillSpeedPhysics.js';
import { vehicleConfig } from '../VehicleConfig.js';
const sample=(grade,heading=0,speed=8,config={downhillBoostPercent:20,uphillPenaltyPercent:30},travel=null)=>{const p=new HillSpeedPhysics((x,z)=>z*grade);if(travel)p.recordTravel(...travel);let h;for(let i=0;i<600;i++)h=p.update({x:0,z:0,heading,speed,thrust:0,config,dt:1/60});return {p,...h};};
assert.equal(sample(0).modifier,0);
assert.ok(Math.abs(sample(-.35).modifier-.2)<1e-6);
assert.ok(Math.abs(sample(.35).modifier+.3)<1e-6);
assert.ok(Math.abs(sample(.35,0,-8).modifier-.2)<1e-6,'reverse downhill boosts');
assert.ok(Math.abs(sample(-.35,0,-8).modifier+.3)<1e-6,'reverse uphill penalizes');
assert.ok(Math.abs(sample(.35,Math.PI/2).modifier)<1e-6,'cross slope is flat');
assert.ok(Math.abs(sample(.35,0,8,{downhillBoostPercent:20,uphillPenaltyPercent:30},[1,0]).modifier)<1e-6,'measured sliding motion overrides facing');
assert.ok(sample(-.1).modifier<sample(-.2).modifier);
assert.ok(sample(.1).modifier>sample(.2).modifier);
assert.ok(Math.abs(sample(-.35,0,8,vehicleConfig.garbageTruck).modifier-.35)<1e-6);
assert.ok(Math.abs(sample(.35,0,8,vehicleConfig.garbageTruck).modifier+.45)<1e-6);
assert.equal(sample(-.35,0,8,{downhillBoostPercent:0,uphillPenaltyPercent:30}).modifier,0);
assert.equal(sample(.35,0,8,{downhillBoostPercent:20,uphillPenaltyPercent:0}).modifier,0);
const uphill=sample(.35).p;assert.ok(uphill.limitSpeed(21,21,9,.016,21)>14.7,'speed eases toward lower cap');
const down=sample(-.35).p;assert.ok(Math.abs(down.limitSpeed(30,21,9,.016,25.2)-25.2)<1e-5,'boost respects cap');
const flat=sample(0).p;assert.equal(flat.limitSpeed(22,21,9,.016,21),21,'flat cap unchanged');
const smoothing=new HillSpeedPhysics((x,z)=>z*.35);const first=smoothing.update({x:0,z:0,heading:0,speed:10,thrust:1,config:{downhillBoostPercent:20,uphillPenaltyPercent:30},dt:1/60});assert.ok(first.modifier<0&&first.modifier>-.03,'hill onset is smooth');
console.log('PASS: flat, uphill/downhill, reversing, cross-slope, actual slide direction, steepness scaling, both vehicle settings, disabled effects, smooth onset and speed caps.');
