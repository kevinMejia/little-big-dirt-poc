import assert from 'node:assert/strict';
import * as THREE from '../three-test.mjs';
import { TreeCollisionSystem } from '../TreeCollisionSystem.js';
const scene=new THREE.Scene();let hits=0;
const system=new TreeCollisionSystem(scene,{onImpact:()=>hits++,particleLimit:32});
const tree=new THREE.Group();tree.position.set(0,0,5);scene.add(tree);const t=system.addTree(tree,.3,3);
const bounds={radius:1,rear:-1,front:1};
const p=new THREE.Vector3();let speed=system.move(p,0,100,.1,bounds);
assert.ok(p.z<2.71,'high-speed sweep blocks trunk');assert.ok(speed<0,'head-on impact rebounds');assert.equal(hits,1);
assert.ok(system.particles.some(p=>p.life>0),'leaves emitted');
system.update(.05);assert.ok(tree.rotation.x>0,'tree bends away from impact');
const before=p.z;system.move(p,0,-3,.2,bounds);assert.ok(p.z<before,'reverse immediately escapes');
system.react(t,1,0,18);system.update(.05);assert.ok(tree.rotation.z<0,'side hit bends away');
for(let i=0;i<1000;i++)system.update(1/60);
assert.equal(system.active.size,0,'spring settles');assert.equal(tree.rotation.x,0);assert.ok(system.particles.every(p=>p.life<=0));
const glance=new THREE.Vector3(1.25,0,0);const out=system.move(glance,0,12,.4,bounds);assert.ok(glance.z>2.7,'glancing impact slides');assert.ok(out>0,'glancing hit preserves forward motion');
const second=new THREE.Group();second.position.set(10,0,5);scene.add(second);const t2=system.addTree(second,.3,3);system.react(t,0,1,6);system.react(t2,1,0,12);assert.equal(system.active.size,2);
for(let i=0;i<100;i++)system.react(t,0,1,20);assert.equal(system.particles.length,32,'pool remains bounded');
system.dispose();assert.equal(system.grid.size,0);
console.log('PASS: swept blocking, gentle rebound, reverse escape, glancing slide, directional spring/settling, simultaneous reactions, bounded leaf pool, cleanup.');
